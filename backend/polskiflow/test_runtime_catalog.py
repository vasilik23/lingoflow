import json
from io import StringIO
from pathlib import Path

from django.conf import settings
from django.core.management import call_command
from django.test import SimpleTestCase

from polskiflow.runtime_catalog import browser_sources, runtime_catalog


class RuntimeCatalogTests(SimpleTestCase):
    def test_projection_keeps_literals_tables_escaped_strings_and_dynamic_keys(self):
        messages = {'Обычный текст': 'plain', 'Ошибка "записи"': 'quoted',
                    "Ответ 'ученика'": 'single', 'Строка\nдва': 'newline',
                    'Динамический статус': 'dynamic', 'Слов: %(v0)s': 'Words: %(v0)s',
                    'Неиспользуемый серверный абзац': 'server'}
        sources = ['const labels = ["Обычный текст", "Ошибка \\"записи\\""];',
                   "ui('Ответ \\'ученика\\''); ui('Строка\\nдва');"]
        selected = runtime_catalog(messages, sources, ['Динамический статус'])
        self.assertEqual(set(selected), set(messages) - {'Неиспользуемый серверный абзац'})
        for key in selected:
            self.assertEqual(selected[key], messages[key])

    def test_ascii_escaped_keys_and_unknown_dynamic_message(self):
        self.assertEqual(runtime_catalog({'Ошибка': 'error'}, [json.dumps('Ошибка')], []), {'Ошибка': 'error'})
        self.assertEqual(runtime_catalog({'Ответ "да" / нет': 'reply'},
                         [r'ui("Ответ \x22да\x22 \/ нет")'], []), {'Ответ "да" / нет': 'reply'})
        self.assertEqual(runtime_catalog({'Длинный текст': 'long'}, ['ui("Длинный \\\nтекст")'], []), {'Длинный текст': 'long'})
        for manifest in (['Неизвестный статус'], 'status', [42]):
            with self.assertRaises(ValueError):
                runtime_catalog({'Ошибка': 'error'}, [], manifest)

    def test_generated_runtime_matches_authoritative_catalogue_and_is_smaller(self):
        backend = Path(settings.BASE_DIR)
        dynamic = json.loads((backend / 'polskiflow/localization/browser_messages.json').read_text())
        for language in ('pl', 'en'):
            call_command('build_ui_catalog', language=language, check=True, stdout=StringIO())
            def read(suffix):
                path = backend / f'polskiflow/learning/static/polskiflow/i18n-{suffix}.js'
                return path.read_text(), json.loads(path.read_text().split(' = ', 1)[1].removesuffix(';\n'))
            full_source, full = read(language)
            runtime_source, actual = read('runtime-' + language)
            self.assertEqual(actual, runtime_catalog(full, browser_sources(backend), dynamic))
            self.assertLess(len(runtime_source.encode()), len(full_source.encode()) * .6)
            self.assertTrue(set(dynamic).issubset(actual))
            self.assertTrue({key for key in full if '%(v' in key}.issubset(actual))

    def test_generated_assets_cannot_retain_removed_keys_through_self_reference(self):
        sources = browser_sources(Path(settings.BASE_DIR))
        self.assertFalse(any('Generated by manage.py build_ui_catalog' in text for text in sources))
